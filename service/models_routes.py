class RouteProbeCheck(TapisApiModel):
    ok: bool = Field(..., description="True when an HTTP response came back (any status). False = could not connect.")
    status_code: Optional[int] = Field(None, description="HTTP status returned, when ok.")
    latency_ms: Optional[int] = Field(None, description="Round-trip time in milliseconds, when ok.")
    error: Optional[str] = Field(None, description="Connection error string, when not ok.")
    snippet: Optional[str] = Field(None, description="First bytes of the response body (sanitized), when ok.")


class RouteProbeResult(TapisApiModel):
    route_id: str
    url: str = Field(..., description="Public hostname for the route.")
    tapis_auth: bool = Field(..., description="Whether the route is auth-gated (a 302 on via_proxy then means the auth gate is working).")
    direct: RouteProbeCheck = Field(..., description="Central dialing backend_host:port directly — is the backend itself up?")
    via_proxy: RouteProbeCheck = Field(..., description="Central dialing traefik with the route's public Host header — is the full public path rendered and routing?")


